import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const inventoryPath = path.resolve(root, 'artifacts/native/release-inventory.json');
const checksumsPath = path.resolve(root, 'artifacts/native/SHA256SUMS');
const outputPath = path.resolve(root, 'docs/releases/go-core-migration-verification.md');
const fixturePath = path.resolve(root, 'tests/fixtures/node-0.1.x.db');

const inventory = JSON.parse(await readFile(inventoryPath, 'utf8'));
const checksums = (await readFile(checksumsPath, 'utf8')).trim();
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const shortCommit = commit.slice(0, 12);
const generatedAt = new Date().toISOString();

let fixtureEvidence = 'Not present in this checkout.';
try {
  const bytes = await readFile(fixturePath);
  fixtureEvidence = `${createHash('sha256').update(bytes).digest('hex')} (${(await stat(fixturePath)).size} bytes)`;
} catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}

const artifactRows = inventory.artifacts
  .map(
    (artifact) =>
      `| \`${artifact.target}\` | \`${artifact.filename}\` | ${artifact.sizeBytes} | \`${artifact.sha256}\` |`,
  )
  .join('\n');

const content = `# Go Core Migration Verification

> Generated by \`pnpm go:write-release-evidence\` from the native release inventory.

## Release identity

- Generated at: \`${generatedAt}\`
- Git commit: \`${commit}\`
- Short commit: \`${shortCommit}\`
- Synaploom version: \`${inventory.version}\`
- Compatibility schema: \`${inventory.schema}\`
- Go toolchain target: \`1.26.5\`
- Course Schema accepted by this release: \`1.0\` and \`1.1.0\`

## Native artifact inventory

| Target | Artifact | Size (bytes) | SHA-256 |
| --- | --- | ---: | --- |
${artifactRows}

The canonical checksum file generated with these binaries is:

\`\`\`text
${checksums}
\`\`\`

## Migration fixture

- Archived Node 0.1.x database fixture: ${fixtureEvidence}

## Hierarchical progression acceptance scope

The release must validate:

- Course Schema 1.0 normalization into an implicit chapter.
- Course Schema 1.1 explicit chapters, optional lessons, and chapter assessments.
- Restart persistence of best and latest practice outcomes.
- Failed review attempts do not revoke an earlier passing best result.
- Completed lesson review does not mutate the persisted current lesson.
- Required chapter assessments gate chapter completion and the next required chapter.
- Canonical chapter-aware deep links and compatibility redirects.
- Backend-authored next actions rendered as a single primary CTA.

## Required manual verification commands

Run these commands from a clean checkout at commit \`${shortCommit}\` and record the output in the test report returned to the implementation agent:

\`\`\`bash
pnpm install --frozen-lockfile
pnpm format:check
pnpm lint
pnpm typecheck
pnpm test
pnpm contracts:check
pnpm go:test
pnpm go:vet
pnpm go:staticcheck
pnpm go:stage-web
pnpm playwright test --project=go-runtime
pnpm go:release
pnpm go:verify-release
pnpm go:write-release-evidence
git status --short
\`\`\`

For the race detector, run packages separately if the aggregate command exceeds the machine limit:

\`\`\`bash
bash scripts/go/with-internal-toolchain.sh test -race ./internal/...
bash scripts/go/with-internal-toolchain.sh test -race ./tests/go-integration/...
\`\`\`

## Environment behavior

In restricted environments, \`scripts/go/with-internal-toolchain.sh\` installs Go 1.26.5 from the configured internal Artifactory, forces \`GOTOOLCHAIN=local\`, and keeps module downloads on the configured internal Go proxy. CI uses the toolchain installed by \`actions/setup-go\`.
`;

await writeFile(outputPath, content);
console.log(`wrote ${path.relative(root, outputPath)}`);
