import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { compileFromFile } from 'json-schema-to-typescript';
import prettier from 'prettier';

const root = process.cwd();
const schemaDir = path.join(root, 'schemas/v1');
const output = path.join(root, 'generated/typescript/index.ts');
const files = (await readdir(schemaDir)).filter((name) => name.endsWith('.schema.json')).sort();
const namespaces = new Map([
  ['activity-attempt.schema.json', 'ActivityAttemptSchema'],
  ['activity-public.schema.json', 'ActivityPublicSchema'],
  ['activity.schema.json', 'ActivityDefinitionSchema'],
  ['lesson-document.schema.json', 'LessonDocumentSchema'],
]);
const chunks = [];
for (const file of files) {
  const source = await compileFromFile(path.join(schemaDir, file), {
    bannerComment: '',
    unreachableDefinitions: true,
    style: { singleQuote: true, semi: true, trailingComma: 'all' },
  });
  const namespace = namespaces.get(file);
  if (namespace) {
    const indented = source
      .trim()
      .split('\n')
      .map((line) => `  ${line}`)
      .join('\n');
    chunks.push(
      `// Generated from schemas/v1/${file}.\nexport namespace ${namespace} {\n${indented}\n}\n`,
    );
  } else {
    chunks.push(`// Generated from schemas/v1/${file}.\n${source.trim()}\n`);
  }
}
chunks.push(`// Stable aliases for namespaced rich-content and activity contracts.
export type ActivityAnswer = ActivityAttemptSchema.ActivityAnswer;
export type ActivityAttempt = ActivityAttemptSchema.ActivityAttempt;
export type ActivityFeedback = ActivityAttemptSchema.ActivityFeedback;
export type ActivityFeedbackItem = ActivityAttemptSchema.ActivityFeedbackItem;
export type ActivitySetProgress = ActivityAttemptSchema.ActivitySetProgress;
export type ActivityPublicView = ActivityPublicSchema.ActivityPublicView;
export type ActivityDefinition = ActivityDefinitionSchema.ActivityDefinition;
export type ActivityKind = ActivityDefinitionSchema.ActivityKind;
export type ActivityEvaluationPolicy = ActivityDefinitionSchema.ActivityEvaluationPolicy;
export type ActivityCompletionPolicy = ActivityDefinitionSchema.ActivityCompletionPolicy;
export type ActivityFeedbackPolicy = ActivityDefinitionSchema.ActivityFeedbackPolicy;
export type ActivitySetPolicy = ActivityDefinitionSchema.ActivitySetPolicy;
export type ActivityReference = ActivityDefinitionSchema.ActivityReference;
export type ActivitySetDefinition = ActivityDefinitionSchema.ActivitySetDefinition;
export type LessonDocument = LessonDocumentSchema.LessonDocument;
export type LessonDocumentFragment = LessonDocumentSchema.LessonDocumentFragment;
`);
let result = `// Code generated by scripts/contracts/generate-typescript.mjs. DO NOT EDIT.\n\n${chunks.join('\n')}`;
result = await prettier.format(result, {
  ...(await prettier.resolveConfig(output)),
  filepath: output,
});
await writeFile(output, result);
