import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { compileFromFile } from 'json-schema-to-typescript';
import prettier from 'prettier';

const root = process.cwd();
const schemaDir = path.join(root, 'schemas/v1');
const output = path.join(root, 'generated/typescript/index.ts');
const files = (await readdir(schemaDir)).filter((name) => name.endsWith('.schema.json')).sort();
const chunks = [];
for (const file of files) {
  const source = await compileFromFile(path.join(schemaDir, file), {
    bannerComment: '',
    unreachableDefinitions: true,
    style: { singleQuote: true, semi: true, trailingComma: 'all' },
  });
  chunks.push(`// Generated from schemas/v1/${file}.\n${source.trim()}\n`);
}
let result = `// Code generated by scripts/contracts/generate-typescript.mjs. DO NOT EDIT.\n\n${chunks.join('\n')}`;
result = await prettier.format(result, {
  ...(await prettier.resolveConfig(output)),
  filepath: output,
});
await writeFile(output, result);
